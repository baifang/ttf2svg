//! Wavefront OBJ export of glyph meshes.
//!
//! One `o` object is written per glyph. Vertices stay in font units and keep
//! the SVG y-down convention; 2D meshes are emitted at `z = 0`.

use std::fmt::Write as _;

use crate::codegen::GlyphMesh;
use crate::mesh::Mesh;

/// Renders all meshes as a single OBJ document.
pub fn render(entries: &[GlyphMesh]) -> String {
    let dimensions = entries.first().map_or(2, |entry| entry.mesh.dimensions());
    let mut out = String::new();

    let _ = writeln!(out, "# Generated by svg2mesh. Do not edit.");
    let _ = writeln!(
        out,
        "# {} meshes, {}D{}",
        entries.len(),
        dimensions,
        if dimensions == 3 {
            ", one normal per face"
        } else {
            ""
        }
    );
    let _ = writeln!(out, "# y axis points down (SVG convention)");
    let _ = writeln!(out);

    let mut vertex_offset = 1_usize;
    let mut normal_offset = 1_usize;

    for entry in entries {
        let _ = writeln!(out, "o {}", object_name(&entry.name));

        match &entry.mesh {
            Mesh::Two(mesh) => {
                for point in &mesh.vertices {
                    let _ = writeln!(out, "v {} {} 0", number(point[0]), number(point[1]));
                }
                for triangle in mesh.indices.chunks_exact(3) {
                    let a = vertex_offset + triangle[0] as usize;
                    let b = vertex_offset + triangle[1] as usize;
                    let c = vertex_offset + triangle[2] as usize;
                    let _ = writeln!(out, "f {a} {b} {c}");
                }
                vertex_offset += mesh.vertices.len();
            }
            Mesh::Three(mesh) => {
                for point in &mesh.vertices {
                    let _ = writeln!(
                        out,
                        "v {} {} {}",
                        number(point[0]),
                        number(point[1]),
                        number(point[2])
                    );
                }
                for normal in &mesh.normals {
                    let _ = writeln!(
                        out,
                        "vn {} {} {}",
                        number(normal[0]),
                        number(normal[1]),
                        number(normal[2])
                    );
                }
                for (index, triangle) in mesh.indices.chunks_exact(3).enumerate() {
                    let normal = normal_offset + index;
                    let a = vertex_offset + triangle[0] as usize;
                    let b = vertex_offset + triangle[1] as usize;
                    let c = vertex_offset + triangle[2] as usize;
                    let _ = writeln!(out, "f {a}//{normal} {b}//{normal} {c}//{normal}");
                }
                vertex_offset += mesh.vertices.len();
                normal_offset += mesh.normals.len();
            }
        }

        let _ = writeln!(out);
    }

    out
}

fn number(value: f64) -> String {
    let value = if value == 0.0 { 0.0 } else { value };
    format!("{value:.6}")
}

fn object_name(name: &str) -> String {
    let mut out = String::new();
    for character in name.chars() {
        if character.is_whitespace() || character == '#' {
            out.push('_');
        } else {
            out.push(character);
        }
    }
    if out.is_empty() {
        "glyph".to_owned()
    } else {
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::mesh::{build_2d, build_3d};
    use crate::svgpath::{parse_path, Transform};

    fn entries(mesh: Mesh) -> Vec<GlyphMesh> {
        vec![GlyphMesh {
            name: "U+0041".to_owned(),
            code_point: Some(0x41),
            mesh,
        }]
    }

    fn square_segments() -> Vec<crate::svgpath::Segment> {
        parse_path("M0 0 H10 V10 H0 Z", Transform::IDENTITY).expect("valid")
    }

    fn face_vertices(obj: &str) -> Vec<usize> {
        obj.lines()
            .filter(|line| line.starts_with("f "))
            .flat_map(|line| {
                line[2..]
                    .split_whitespace()
                    .map(|token| token.split("//").next().expect("vertex").to_owned())
                    .collect::<Vec<_>>()
            })
            .map(|token| token.parse::<usize>().expect("index"))
            .collect()
    }

    #[test]
    fn writes_2d_objects() {
        let mesh = Mesh::Two(build_2d(&square_segments(), 0.5).expect("mesh"));
        let obj = render(&entries(mesh));

        assert!(obj.contains("# 1 meshes, 2D"), "{obj}");
        assert!(obj.contains("o U+0041"), "{obj}");
        assert_eq!(obj.lines().filter(|line| line.starts_with("v ")).count(), 4);
        assert_eq!(obj.lines().filter(|line| line.starts_with("f ")).count(), 2);
        assert!(!obj.contains("vn "), "{obj}");

        let vertices = 4;
        assert!(face_vertices(&obj)
            .iter()
            .all(|index| *index >= 1 && *index <= vertices));
    }

    #[test]
    fn writes_3d_objects_with_normals() {
        let mesh = Mesh::Three(build_3d(&square_segments(), 0.5, 5.0).expect("mesh"));
        let obj = render(&entries(mesh));

        assert!(obj.contains("# 1 meshes, 3D, one normal per face"), "{obj}");
        assert_eq!(obj.lines().filter(|line| line.starts_with("v ")).count(), 8);
        assert_eq!(
            obj.lines().filter(|line| line.starts_with("vn ")).count(),
            12
        );
        assert_eq!(
            obj.lines().filter(|line| line.starts_with("f ")).count(),
            12
        );
        for (index, line) in obj
            .lines()
            .filter(|line| line.starts_with("f "))
            .enumerate()
        {
            let expected = format!("//{}", index + 1);
            assert!(
                line.split_whitespace()
                    .skip(1)
                    .all(|token| token.ends_with(&expected)),
                "{line}"
            );
        }

        let vertices = 8;
        assert!(face_vertices(&obj)
            .iter()
            .all(|index| *index >= 1 && *index <= vertices));
    }

    #[test]
    fn offsets_indices_across_objects() {
        let segments = square_segments();
        let first = Mesh::Two(build_2d(&segments, 0.5).expect("mesh"));
        let second = Mesh::Two(build_2d(&segments, 0.5).expect("mesh"));
        let entries = vec![
            GlyphMesh {
                name: "U+0041".to_owned(),
                code_point: Some(0x41),
                mesh: first,
            },
            GlyphMesh {
                name: "U+0042".to_owned(),
                code_point: Some(0x42),
                mesh: second,
            },
        ];

        let obj = render(&entries);
        let vertices = 8;
        assert!(face_vertices(&obj)
            .iter()
            .all(|index| *index >= 1 && *index <= vertices));
        assert!(obj.contains("f 5 6 7"), "{obj}");
    }

    #[test]
    fn sanitizes_object_names() {
        assert_eq!(object_name("my glyph #1"), "my_glyph__1");
        assert_eq!(object_name(""), "glyph");
    }
}
