//! Generation of C and Rust source files describing glyph meshes.

use std::fmt::Write as _;

use thiserror::Error;

use crate::mesh::{Mesh, MeshError};

/// One glyph to emit.
#[derive(Debug, Clone)]
pub struct GlyphMesh {
    pub name: String,
    pub code_point: Option<u32>,
    pub mesh: Mesh,
}

#[derive(Debug, Error)]
pub enum CodegenError {
    #[error("no glyph meshes to write")]
    Empty,

    #[error(transparent)]
    Mesh(#[from] MeshError),
}

/// Builds the `.h` and `.c` contents for `entries`.
pub fn generate(basename: &str, entries: &[GlyphMesh]) -> Result<(String, String), CodegenError> {
    let dimensions = dimensions_and_validate(entries)?;

    let guard = guard_name(basename);
    let header = render_header(basename, &guard, entries, dimensions);
    let source = render_source(basename, entries, dimensions);

    Ok((header, source))
}

/// Builds the `.rs` module contents for `entries`.
pub fn generate_rust(basename: &str, entries: &[GlyphMesh]) -> Result<String, CodegenError> {
    let dimensions = dimensions_and_validate(entries)?;
    Ok(render_rust(basename, entries, dimensions))
}

fn dimensions_and_validate(entries: &[GlyphMesh]) -> Result<u8, CodegenError> {
    let Some(first) = entries.first() else {
        return Err(CodegenError::Empty);
    };
    let dimensions = first.mesh.dimensions();

    for entry in entries {
        let vertex_count = match &entry.mesh {
            Mesh::Two(mesh) => mesh.vertices.len(),
            Mesh::Three(mesh) => mesh.vertices.len(),
        };
        if vertex_count > usize::from(u16::MAX) {
            return Err(MeshError::TooManyVertices(vertex_count).into());
        }
    }

    Ok(dimensions)
}

fn render_header(basename: &str, guard: &str, entries: &[GlyphMesh], dimensions: u8) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "/* Generated by svg2mesh ({basename}.c). Do not edit. */"
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "#ifndef {guard}");
    let _ = writeln!(out, "#define {guard}");
    let _ = writeln!(out);
    let _ = writeln!(out, "#include <stddef.h>");
    let _ = writeln!(out, "#include <stdint.h>");
    let _ = writeln!(out);
    let _ = writeln!(out, "#define SVG_MESH_COUNT {}u", entries.len());
    let _ = writeln!(out, "#define SVG_MESH_DIMENSIONS {dimensions}u");
    let _ = writeln!(out);
    let _ = writeln!(out, "#ifdef __cplusplus");
    let _ = writeln!(out, "extern \"C\" {{");
    let _ = writeln!(out, "#endif");
    let _ = writeln!(out);
    let _ = writeln!(out, "typedef struct {{");
    let _ = writeln!(out, "    const char *name;");
    let _ = writeln!(out, "    uint32_t code_point;");
    let _ = writeln!(out, "    float min_x;");
    let _ = writeln!(out, "    float min_y;");
    let _ = writeln!(out, "    float max_x;");
    let _ = writeln!(out, "    float max_y;");
    let _ = writeln!(out, "    const float *vertices;");
    let _ = writeln!(out, "    uint32_t vertex_count;");
    let _ = writeln!(out, "    const uint16_t *indices;");
    let _ = writeln!(out, "    uint32_t index_count;");
    let _ = writeln!(out, "    const float *normals;");
    let _ = writeln!(out, "}} svg_mesh;");
    let _ = writeln!(out);
    let _ = writeln!(out, "extern const svg_mesh svg_meshes[SVG_MESH_COUNT];");
    let _ = writeln!(out);
    let _ = writeln!(out, "const svg_mesh *svg_mesh_find(uint32_t code_point);");
    let _ = writeln!(out);
    let _ = writeln!(out, "#ifdef __cplusplus");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out, "#endif");
    let _ = writeln!(out);
    let _ = writeln!(out, "#endif /* {guard} */");
    out
}

fn render_source(basename: &str, entries: &[GlyphMesh], dimensions: u8) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "/* Generated by svg2mesh. Do not edit. */");
    let _ = writeln!(out);
    let _ = writeln!(out, "#include \"{basename}.h\"");
    let _ = writeln!(out);

    for (index, entry) in entries.iter().enumerate() {
        write_arrays(&mut out, index, &entry.mesh);
    }

    let _ = writeln!(out, "const svg_mesh svg_meshes[SVG_MESH_COUNT] = {{");
    for (index, entry) in entries.iter().enumerate() {
        let [min_x, min_y, max_x, max_y] = bounds(&entry.mesh);
        let (vertex_count, index_count) = match &entry.mesh {
            Mesh::Two(mesh) => (mesh.vertices.len(), mesh.indices.len()),
            Mesh::Three(mesh) => (mesh.vertices.len(), mesh.indices.len()),
        };
        let normals = if dimensions == 3 {
            format!("svg_mesh_{index}_normals")
        } else {
            "NULL".to_owned()
        };
        let code_point = match entry.code_point {
            Some(value) => format!("0x{value:X}u"),
            None => "0u".to_owned(),
        };

        let _ = writeln!(out, "    {{");
        let _ = writeln!(out, "        {},", c_string(&entry.name));
        let _ = writeln!(out, "        {code_point},");
        let _ = writeln!(
            out,
            "        {}, {}, {}, {},",
            c_float(min_x),
            c_float(min_y),
            c_float(max_x),
            c_float(max_y)
        );
        let _ = writeln!(out, "        svg_mesh_{index}_vertices,");
        let _ = writeln!(out, "        {vertex_count}u,");
        let _ = writeln!(out, "        svg_mesh_{index}_indices,");
        let _ = writeln!(out, "        {index_count}u,");
        let _ = writeln!(out, "        {normals}");
        let _ = writeln!(out, "    }},");
    }
    let _ = writeln!(out, "}};");
    let _ = writeln!(out);
    let _ = writeln!(out, "const svg_mesh *svg_mesh_find(uint32_t code_point)");
    let _ = writeln!(out, "{{");
    let _ = writeln!(out, "    size_t index;");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    for (index = 0; index < SVG_MESH_COUNT; ++index) {{"
    );
    let _ = writeln!(
        out,
        "        if (svg_meshes[index].code_point == code_point) {{"
    );
    let _ = writeln!(out, "            return &svg_meshes[index];");
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "    return NULL;");
    let _ = writeln!(out, "}}");
    out
}

fn write_arrays(out: &mut String, index: usize, mesh: &Mesh) {
    match mesh {
        Mesh::Two(mesh) => {
            let vertices = mesh
                .vertices
                .iter()
                .flat_map(|point| [c_float(point[0]), c_float(point[1])])
                .collect::<Vec<_>>();
            write_array(out, &format!("float svg_mesh_{index}_vertices"), &vertices);

            let indices = mesh.indices.iter().map(u32::to_string).collect::<Vec<_>>();
            write_array(out, &format!("uint16_t svg_mesh_{index}_indices"), &indices);
        }
        Mesh::Three(mesh) => {
            let vertices = mesh
                .vertices
                .iter()
                .flat_map(|point| [c_float(point[0]), c_float(point[1]), c_float(point[2])])
                .collect::<Vec<_>>();
            write_array(out, &format!("float svg_mesh_{index}_vertices"), &vertices);

            let indices = mesh.indices.iter().map(u32::to_string).collect::<Vec<_>>();
            write_array(out, &format!("uint16_t svg_mesh_{index}_indices"), &indices);

            let normals = mesh
                .normals
                .iter()
                .flat_map(|normal| [c_float(normal[0]), c_float(normal[1]), c_float(normal[2])])
                .collect::<Vec<_>>();
            write_array(out, &format!("float svg_mesh_{index}_normals"), &normals);
        }
    }
}

fn write_array(out: &mut String, declaration: &str, values: &[String]) {
    let _ = writeln!(out, "static const {declaration}[] = {{");
    for chunk in values.chunks(8) {
        let _ = writeln!(out, "    {},", chunk.join(", "));
    }
    let _ = writeln!(out, "}};");
    let _ = writeln!(out);
}

fn bounds(mesh: &Mesh) -> [f64; 4] {
    match mesh {
        Mesh::Two(mesh) => mesh.bounds,
        Mesh::Three(mesh) => mesh.bounds,
    }
}

fn c_float(value: f64) -> String {
    let value = if value == 0.0 { 0.0 } else { value };
    format!("{value:.6}f")
}

fn c_string(value: &str) -> String {
    let mut out = String::from("\"");
    for character in value.chars() {
        match character {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            character if character.is_control() => {
                let _ = write!(out, "\\x{:02x}", character as u32);
            }
            character => out.push(character),
        }
    }
    out.push('"');
    out
}

fn guard_name(basename: &str) -> String {
    let mut guard = String::from("SVG_MESH_");
    for character in basename.chars() {
        if character.is_ascii_alphanumeric() {
            guard.push(character.to_ascii_uppercase());
        } else {
            guard.push('_');
        }
    }
    guard.push_str("_H");
    guard
}

fn render_rust(basename: &str, entries: &[GlyphMesh], dimensions: u8) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "//! Generated by svg2mesh ({basename}.rs). Do not edit."
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "/// One triangulated glyph.");
    let _ = writeln!(out, "#[allow(dead_code)]");
    let _ = writeln!(out, "#[derive(Debug, Clone, Copy)]");
    let _ = writeln!(out, "pub struct Mesh {{");
    let _ = writeln!(out, "    /// Glyph name (the source file stem).");
    let _ = writeln!(out, "    pub name: &'static str,");
    let _ = writeln!(
        out,
        "    /// Unicode code point parsed from a `U+XXXX` name, or 0."
    );
    let _ = writeln!(out, "    pub code_point: u32,");
    let _ = writeln!(out, "    /// `[min_x, min_y, max_x, max_y]` in font units.");
    let _ = writeln!(out, "    pub bounds: [f32; 4],");
    let _ = writeln!(out, "    /// Two floats per vertex in 2D, three in 3D.");
    let _ = writeln!(out, "    pub vertices: &'static [f32],");
    let _ = writeln!(out, "    /// Three indices per triangle.");
    let _ = writeln!(out, "    pub indices: &'static [u16],");
    let _ = writeln!(
        out,
        "    /// Three floats per triangle in 3D; `None` in 2D."
    );
    let _ = writeln!(out, "    pub normals: Option<&'static [f32]>,");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let _ = writeln!(out, "#[allow(dead_code)]");
    let _ = writeln!(out, "impl Mesh {{");
    let _ = writeln!(out, "    /// Number of triangles in this mesh.");
    let _ = writeln!(out, "    pub fn triangle_count(&self) -> usize {{");
    let _ = writeln!(out, "        self.indices.len() / 3");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let _ = writeln!(out, "/// Number of floats per vertex in this build.");
    let _ = writeln!(out, "#[allow(dead_code)]");
    let _ = writeln!(out, "pub const DIMENSIONS: usize = {dimensions};");
    let _ = writeln!(out);
    let _ = writeln!(out, "/// Number of meshes in this module.");
    let _ = writeln!(out, "#[allow(dead_code)]");
    let _ = writeln!(out, "pub const COUNT: usize = {};", entries.len());
    let _ = writeln!(out);

    for (index, entry) in entries.iter().enumerate() {
        write_rust_arrays(&mut out, index, &entry.mesh);
    }

    let _ = writeln!(out, "/// All glyph meshes, sorted by code point.");
    let _ = writeln!(out, "#[allow(dead_code)]");
    let _ = writeln!(out, "pub static MESHES: &[Mesh] = &[");
    for (index, entry) in entries.iter().enumerate() {
        let [min_x, min_y, max_x, max_y] = bounds(&entry.mesh);
        let normals = if dimensions == 3 {
            format!("Some(&MESH_{index}_NORMALS)")
        } else {
            "None".to_owned()
        };
        let code_point = match entry.code_point {
            Some(value) => format!("0x{value:X}"),
            None => "0".to_owned(),
        };

        let _ = writeln!(out, "    Mesh {{");
        let _ = writeln!(out, "        name: {},", c_string(&entry.name));
        let _ = writeln!(out, "        code_point: {code_point},");
        let _ = writeln!(
            out,
            "        bounds: [{}, {}, {}, {}],",
            rust_float(min_x),
            rust_float(min_y),
            rust_float(max_x),
            rust_float(max_y)
        );
        let _ = writeln!(out, "        vertices: &MESH_{index}_VERTICES,");
        let _ = writeln!(out, "        indices: &MESH_{index}_INDICES,");
        let _ = writeln!(out, "        normals: {normals},");
        let _ = writeln!(out, "    }},");
    }
    let _ = writeln!(out, "];");
    let _ = writeln!(out);
    let _ = writeln!(out, "/// Looks up a mesh by Unicode code point.");
    let _ = writeln!(out, "#[allow(dead_code)]");
    let _ = writeln!(
        out,
        "pub fn find(code_point: u32) -> Option<&'static Mesh> {{"
    );
    let _ = writeln!(
        out,
        "    MESHES.iter().find(|mesh| mesh.code_point == code_point)"
    );
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let _ = writeln!(out, "/// Looks up a mesh by its source file name.");
    let _ = writeln!(out, "#[allow(dead_code)]");
    let _ = writeln!(
        out,
        "pub fn find_by_name(name: &str) -> Option<&'static Mesh> {{"
    );
    let _ = writeln!(out, "    MESHES.iter().find(|mesh| mesh.name == name)");
    let _ = writeln!(out, "}}");
    out
}

fn write_rust_arrays(out: &mut String, index: usize, mesh: &Mesh) {
    match mesh {
        Mesh::Two(mesh) => {
            let vertices = mesh
                .vertices
                .iter()
                .flat_map(|point| [rust_float(point[0]), rust_float(point[1])])
                .collect::<Vec<_>>();
            write_rust_array(out, &format!("MESH_{index}_VERTICES"), "f32", &vertices);

            let indices = mesh.indices.iter().map(u32::to_string).collect::<Vec<_>>();
            write_rust_array(out, &format!("MESH_{index}_INDICES"), "u16", &indices);
        }
        Mesh::Three(mesh) => {
            let vertices = mesh
                .vertices
                .iter()
                .flat_map(|point| {
                    [
                        rust_float(point[0]),
                        rust_float(point[1]),
                        rust_float(point[2]),
                    ]
                })
                .collect::<Vec<_>>();
            write_rust_array(out, &format!("MESH_{index}_VERTICES"), "f32", &vertices);

            let indices = mesh.indices.iter().map(u32::to_string).collect::<Vec<_>>();
            write_rust_array(out, &format!("MESH_{index}_INDICES"), "u16", &indices);

            let normals = mesh
                .normals
                .iter()
                .flat_map(|normal| {
                    [
                        rust_float(normal[0]),
                        rust_float(normal[1]),
                        rust_float(normal[2]),
                    ]
                })
                .collect::<Vec<_>>();
            write_rust_array(out, &format!("MESH_{index}_NORMALS"), "f32", &normals);
        }
    }
}

fn write_rust_array(out: &mut String, name: &str, element: &str, values: &[String]) {
    let _ = writeln!(out, "#[allow(dead_code)]");
    let _ = writeln!(out, "static {name}: [{element}; {}] = [", values.len());
    for chunk in values.chunks(6) {
        let _ = writeln!(out, "    {},", chunk.join(", "));
    }
    let _ = writeln!(out, "];");
    let _ = writeln!(out);
}

fn rust_float(value: f64) -> String {
    let value = if value == 0.0 { 0.0 } else { value };
    format!("{value:.6}")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::mesh::build_2d;
    use crate::svgpath::{parse_path, Transform};

    fn square() -> Mesh {
        let segments = parse_path("M0 0 H10 V10 H0 Z", Transform::IDENTITY).expect("valid");
        Mesh::Two(build_2d(&segments, 0.5).expect("mesh"))
    }

    #[test]
    fn writes_a_header_and_source() {
        let entries = vec![GlyphMesh {
            name: "U+0041".to_owned(),
            code_point: Some(0x41),
            mesh: square(),
        }];
        let (header, source) = generate("glyphs", &entries).expect("generated");

        assert!(header.contains("#define SVG_MESH_DIMENSIONS 2u"));
        assert!(header.contains("#define SVG_MESH_COUNT 1u"));
        assert!(header.contains("typedef struct"));
        assert!(header.contains("const svg_mesh *svg_mesh_find(uint32_t code_point);"));

        assert!(source.contains("#include \"glyphs.h\""));
        assert!(source.contains("static const float svg_mesh_0_vertices[]"));
        assert!(source.contains("static const uint16_t svg_mesh_0_indices[]"));
        assert!(source.contains("\"U+0041\""));
        assert!(source.contains("0x41u"));
        assert!(source.contains("NULL"));
    }

    #[test]
    fn writes_a_rust_module() {
        let entries = vec![GlyphMesh {
            name: "U+0041".to_owned(),
            code_point: Some(0x41),
            mesh: square(),
        }];
        let source = generate_rust("glyphs", &entries).expect("generated");

        assert!(source.contains("pub struct Mesh"));
        assert!(source.contains("pub const DIMENSIONS: usize = 2;"));
        assert!(source.contains("pub const COUNT: usize = 1;"));
        assert!(source.contains("pub static MESHES: &[Mesh]"));
        assert!(source.contains("pub fn find(code_point: u32)"));
        assert!(source.contains("pub fn find_by_name(name: &str)"));
        assert!(source.contains("name: \"U+0041\""));
        assert!(source.contains("code_point: 0x41"));
        assert!(source.contains("normals: None"));
    }

    #[test]
    fn rust_3d_meshes_expose_normals() {
        let segments = parse_path("M0 0 H10 V10 H0 Z", Transform::IDENTITY).expect("valid");
        let mesh = Mesh::Three(crate::mesh::build_3d(&segments, 0.5, 5.0).expect("mesh"));
        let entries = vec![GlyphMesh {
            name: "square".to_owned(),
            code_point: None,
            mesh,
        }];

        let source = generate_rust("glyphs", &entries).expect("generated");

        assert!(source.contains("pub const DIMENSIONS: usize = 3;"));
        assert!(source.contains("Some(&MESH_0_NORMALS)"));
        assert!(source.contains("code_point: 0,"));
    }

    #[test]
    fn rejects_empty_input() {
        assert!(matches!(generate("glyphs", &[]), Err(CodegenError::Empty)));
    }
}
